def gfm_anchor(text):
    """GitHub 风格锚点（与 fix_toc.py 一致）"""
    text = re.sub(r'(\d+)\.(\d+)', r'\1\2', text)
    text = text.replace('（', '').replace('）', '').replace('(', '').replace(')', '')
