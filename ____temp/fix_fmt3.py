path = '_主文档/MC3.3.5_甲乙己日等型交叉分析报告.md'
with open(path, encoding='utf-8') as f:
    content = f.read()

# 字符串替换：> 验证结果/已验证数据/验证数据（...）： → **...**
repl = [
    ('> 验证结果（2026-09-13，谕组日0911数据2022万行）：', '**验证结果（2026-09-13，谕组日0911数据2022万行）：**'),
    ('> 验证数据（全量，甲乙己）：', '**验证数据（全量，甲乙己）：**'),
    ('> 已验证数据（升管=甲乙己+曾触哼，等3，n=6,398,833，基线 23.01%，推高顶=触顶+升排）：', '**已验证数据（升管=甲乙己+曾触哼，等3，n=6,398,833，基线 23.01%，推高顶=触顶+升排）：**'),
    ('> 已验证数据（甲乙己，n=1,079,080，基线 24.48%）：', '**已验证数据（甲乙己，n=1,079,080，基线 24.48%）：**'),
    ('> 已验证数据（甲乙己，n=1,150,488，基线 21.89%）：', '**已验证数据（甲乙己，n=1,150,488，基线 21.89%）：**'),
    ('> 已验证数据（乙DXZA<0）：', '**已验证数据（乙DXZA<0）：**'),
    ('> 已验证数据（跌管 丙丁戊，全量 7455 文件）：', '**已验证数据（跌管 丙丁戊，全量 7455 文件）：**'),
]
changed = 0
for old, new in repl:
    if old in content:
        content = content.replace(old, new)
        changed += 1
print(f'统一为加粗标题式 {changed} 处')
with open(path, 'w', encoding='utf-8') as f:
    f.write(content)
