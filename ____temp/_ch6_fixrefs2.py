# -*- coding: utf-8 -*-
"""第六章交叉引用更新：重排前编号 → 新编号"""
import re, sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')

SRC = '_主文档/MC3.3.5_甲乙己日等型交叉分析报告.md'
with open(SRC, encoding='utf-8') as f:
    text = f.read()

# 重排前编号 → 新编号（注意：6.1 指指导思想→6.1.1，6.2 指三层漏斗总览→6.1）
num_map = {
    '6.1.1': '6.1.2',   # 操作逻辑
    '6.1':   '6.1.1',   # 指导思想
    '6.2':   '6.1',     # 三层漏斗总览
    '6.3.1.1': '6.2.1.1',
    '6.3.1': '6.2.1',   # 四类区域
    '6.3':   '6.2',     # 第1层
    '6.4':   '6.3',     # 第2层
    '6.5':   '6.4',     # 第3层
    '6.6.2': '6.5.2',
    '6.6.1': '6.5.1',
    '6.6':   '6.5',     # 定型规则
    '6.7':   '6.12.5',  # 期望收益
    '6.8':   '6.12.6',  # 持有条件
    '6.9.3': '6.12.7',  # 少而精剔诱多
    '6.9':   '6.12.7',  # 少而精
    '6.10':  '6.12.8',  # 股性
    '6.11':  '6.4.2',   # 入管依据
    '6.12':  '6.12',    # 旧内容
}

def remap(m):
    num = m.group(1)
    return '§' + num_map.get(num, num)

# 只替换正文引用 §6.x（不碰标题行 ### 6.x）
new_text = re.sub(r'§(6\.\d+(?:\.\d+)?)', remap, text)

with open(SRC, 'w', encoding='utf-8') as f:
    f.write(new_text)

print('✅ 交叉引用已更新')