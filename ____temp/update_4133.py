# -*- coding: utf-8 -*-
import sys
sys.stdout.reconfigure(encoding='utf-8')
path = '_主文档/MC3.1_研究月基策略.md'
with open(path, encoding='utf-8') as f:
    content = f.read()

# 1. 标题: 剩余范围 -> 执念范围
old_title = '#### 4.1.3.3 剩余范围（WXZC>0 + 丙丁戊）'
new_title = '#### 4.1.3.3 执念范围（WXZC>0 + 丙丁戊）'
assert old_title in content, '标题未找到'
content = content.replace(old_title, new_title)

# 2. 定义和逻辑
old_def = '''> **定义：剩余范围 = 全部 - 宽范围 - 禁区范围 = WXZC>0 + 丙丁戊（范围外但非禁区）。**
>
> **逻辑：** 宽范围表"范围外"（丁/戊(ZA≤0)/丙）中，WXZC>0 的部分既不在宽范围（范围内护型）也不在禁区范围（WXZC<0 + 丙丁戊），是剩余范围。

**剩余范围性质：** 剩余范围 = WXZC>0 + 丙丁戊（范围外但非禁区）——**范围外护型（丙丁戊）在 WXZC>0 时仍属范围外**（宽范围表明确"范围外"回避/退出），**不介入**。它与禁区范围（WXZC<0 + 丙丁戊）在 WXZC 维度上互斥，共同覆盖全部丙丁戊护型。'''
new_def = '''> **定义：执念范围 = 全部 - 宽范围 - 禁区范围 = WXZC>0 + 丙丁戊（范围外但非禁区）。**
>
> **逻辑：** 宽范围表"范围外"（丁/戊(ZA≤0)/丙）中，WXZC>0 的部分既不在宽范围（范围内护型）也不在禁区范围（WXZC<0 + 丙丁戊），是执念范围。

**执念范围全量验证（高波池全量，2026-09-04 重跑）：**

| 范围 | 定义 | n | 周冲高≥3% | 平均周高幅 |
|:--|:--|:--|:--|:--|
| **基线（所有样本）** | 全部 | 2,333,568 | 55.41% | 5.16% |
| **宽范围** | 范围内护型 | 1,117,829 | **69.85%** | 7.00% |
| **禁区范围** | WXZC<0 + 丙丁戊 | 1,089,545 | 42.15% | 3.47% |
| **执念范围** | WXZC>0 + 丙丁戊 | 142,655 | 44.72% | 3.58% |

> **结论：执念范围（WXZC>0 + 丙丁戊）周冲高≥3% = 44.72%，明显低于基线（55.41%，-10.69pp），不成立。** 即使 WXZC>0（升势），丙丁戊（差护型）的周冲高仍远低于基线，**不介入**。执念范围与禁区范围（42.15%）都明显低于基线，只有宽范围（69.85%）显著高于基线可介入。**三者互斥且合并 = 全部护型。**'''
assert old_def in content, '定义未找到'
content = content.replace(old_def, new_def)

with open(path, 'w', encoding='utf-8') as f:
    f.write(content)
print('已把 4.1.3.3 剩余范围 改为 执念范围，并补充数据验证')
