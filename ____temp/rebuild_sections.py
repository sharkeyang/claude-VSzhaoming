def get_text(si):
    data = ppt.get(str(si), [])
    texts = []
    for item in data:
        if 'text' in item: texts.append(item['text'])
        if 'children' in item:
            for c in item['children']:
                if 'text' in c: texts.append(c['text'])
                if 'children' in c:
                    for c2 in c['children']:
                        if 'text' in c2: texts.append(c2['text'])
    return texts

def get_tables(si):
    data = ppt.get(str(si), [])
    tables = []
    for item in data:
        if 'table' in item: tables.append(item['table'])
        if 'children' in item:
            for c in item['children']:
                if 'table' in c: tables.append(c['table'])
                if 'children' in c:
                    for c2 in c['children']:
                        if 'table' in c2: tables.append(c2['table'])
    return tables

