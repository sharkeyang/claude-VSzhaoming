# -*- coding: utf-8 -*-
"""恢复丢失的 MC3.1 §5 内容：3.5/3.6/3.7/3.9 → 5.3.7/5.6/5.8/5.7"""
import re

backup = open('____temp/备份_MC3.3_研究日冲策略.md', encoding='utf-8').read()
cur = open('_主文档/MC3.1_研究月基策略.md', encoding='utf-8').read()

def extract(start_marker, end_marker):
    s = backup.find(start_marker)
    e = backup.find(end_marker, s)
    return backup[s:e]

def renum(block, mapping):
    for old, new in mapping.items():
        block = block.replace(old, new)
    return block

# ========== 提取并重编号 ==========
# §3.5 小样本分布规律 → 5.3.7
s35 = extract('### 3.5 小样本分布规律', '### 3.6 综合结论')
s35 = renum(s35, {'### 3.5': '### 5.3.7', '#### 3.5.1': '#### 5.3.7.1', '#### 3.5.2': '#### 5.3.7.2', '#### 3.5.3': '#### 5.3.7.3'})

# §3.6 综合结论 → 5.6
s36 = extract('### 3.6 综合结论', '### 3.7 技术细节')
s36 = renum(s36, {'### 3.6': '### 5.6', '#### 3.6.1': '#### 5.6.1', '#### 3.6.2': '#### 5.6.2', '#### 3.6.3': '#### 5.6.3', '#### 3.6.4': '#### 5.6.4', '#### 3.6.5': '#### 5.6.5', '#### 3.6.6': '#### 5.6.6'})

# §3.7 技术细节 → 5.8
s37 = extract('### 3.7 技术细节', '### 3.8 四级别分类规则验证')
s37 = renum(s37, {'### 3.7': '### 5.8', '#### 3.7.1': '#### 5.8.1', '#### 3.7.2': '#### 5.8.2'})

# §3.9 新旧变量 → 5.7
s39 = extract('### 3.9 新旧变量预测能力对比', '## 四、按形态探索')
s39 = renum(s39, {'### 3.9': '### 5.7', '#### 3.9.1': '#### 5.7.1'})
# 处理重复的 3.9.2
s39 = renum(s39, {'#### 3.9.2 位谕of日层联动 — 20级DJE走势等级\n\n**输出格式：**': '#### 5.7.3 位谕of日层联动 — 20级DJE走势等级\n\n**输出格式：**'})
s39 = renum(s39, {'#### 3.9.2 位谕of日层联动': '#### 5.7.2 位谕of日层联动', '#### 3.9.3': '#### 5.7.4', '#### 3.9.4': '#### 5.7.5'})

# ========== 插入到 MC3.1 §5 ==========
# 5.3.7 插在 5.3.6 DSHR>1 之后、5.4 规则验证之前
anchor_54 = '### 5.4 四级别分类规则验证'
cur = cur.replace(anchor_54, s35 + '\n' + anchor_54)

# 5.6/5.7/5.8 插在 5.5.3 之后、第六章之前
anchor_6 = '## 第六章：VBA实施计划'
cur = cur.replace(anchor_6, s36 + '\n---\n\n' + s37 + '\n---\n\n' + s39 + '\n---\n\n' + anchor_6)

open('_主文档/MC3.1_研究月基策略.md', 'w', encoding='utf-8').write(cur)
print('恢复完成')
